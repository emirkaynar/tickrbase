@asynccontextmanager
async def isolated_database():
    schema = "identity_test_" + uuid4().hex
    admin = create_async_engine(DATABASE_URL, poolclass=NullPool)
    scoped = create_async_engine(DATABASE_URL, poolclass=NullPool, connect_args={"server_settings": {"search_path": schema}})
    created = False
    try:
        async with admin.begin() as conn:
            await conn.execute(text(f'CREATE SCHEMA "{schema}"'))
        created = True
        yield scoped
    finally:
        await scoped.dispose()
        if created:
            # schema is generated locally above, never accepted from a request.
            async with admin.begin() as conn:
                await conn.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
        await admin.dispose()


def test_registration_login_and_me_use_public_ids_with_real_postgres():
    async def run():
        async with isolated_database() as engine:
            async with engine.begin() as conn:
                await conn.run_sync(User.__table__.create)
                await conn.run_sync(AuthSession.__table__.create)
            app = FastAPI()
            app.include_router(router)

            async def database():
                async with AsyncSession(engine, expire_on_commit=False) as session:
                    yield session
                    await session.commit()
            app.dependency_overrides[get_db] = database

            with patch("backend.api.auth.enforce_auth_limits", new=AsyncMock()):
              async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="https://test") as client:
                first = await client.post("/auth/register", json={"email": "first@example.com", "password": "test-password"})
                assert first.status_code == 201
                first_id = UUID(first.json()["id"])
                assert first_id.version == 4
                token = client.cookies["access_token"]
                assert len(token) == 43 and "." not in token
                me = await client.get("/auth/me")
                assert me.json()["id"] == str(first_id)
                second = await client.post("/auth/register", json={"email": "second@example.com", "password": "test-password"})
                assert second.status_code == 201
                assert UUID(second.json()["id"]) != first_id
                login = await client.post("/auth/login", json={"email": "first@example.com", "password": "test-password"})
                assert login.status_code == 200
                assert login.json()["id"] == str(first_id)
                assert (await client.get("/auth/me")).json()["id"] == str(first_id)

            async with AsyncSession(engine) as session:
                user = (await session.execute(select(User).where(User.public_id == first_id))).scalar_one()
                assert isinstance(user.id, int)
                assert user.id != first_id

                with pytest.raises(IntegrityError):
                    await session.execute(insert(User).values(public_id=first_id, email="duplicate@example.com", hashed_password="unused", tier="free"))
                    await session.commit()
    asyncio.run(run())


def test_public_identity_migration_upgrades_and_downgrades_user_table_only():
    migration = importlib.import_module("backend.alembic.versions.008_public_user_identity")

    def apply(conn, command):
        with Operations.context(MigrationContext.configure(conn)):
            command()

    async def run():
        async with isolated_database() as engine:
            async with engine.begin() as conn:
                await conn.execute(text("CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email varchar(255) UNIQUE NOT NULL, hashed_password varchar(255) NOT NULL, tier varchar(50) NOT NULL DEFAULT 'free', created_at timestamptz NOT NULL DEFAULT now())"))
                await conn.run_sync(lambda sync: apply(sync, migration.upgrade))
                await conn.execute(text("INSERT INTO users (email, hashed_password) VALUES ('first@example.com', 'unused'), ('second@example.com', 'unused')"))
                rows = (await conn.execute(text("SELECT id, public_id FROM users ORDER BY id"))).all()
                assert all(isinstance(row.public_id, UUID) and row.public_id.version == 4 for row in rows)
                assert rows[0].public_id != rows[1].public_id
                assert [row.id for row in rows] == [1, 2]
                await conn.run_sync(lambda sync: apply(sync, migration.downgrade))
                assert (await conn.execute(text("SELECT id FROM users ORDER BY id"))).scalars().all() == [1, 2]
                columns = (await conn.execute(text("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='users'"))).scalars().all()
                assert "public_id" not in columns
                tables = (await conn.execute(text("SELECT tablename FROM pg_tables WHERE schemaname=current_schema()"))).scalars().all()
                assert tables == ["users"]
    asyncio.run(run())


def test_session_migration_and_concurrent_registration_race():
    migration = importlib.import_module("backend.alembic.versions.009_auth_sessions")

    def apply(conn, command):
        with Operations.context(MigrationContext.configure(conn)):
            command()

    async def run():
        async with isolated_database() as engine:
            async with engine.begin() as conn:
                await conn.run_sync(User.__table__.create)
                await conn.run_sync(lambda sync: apply(sync, migration.upgrade))
            app = FastAPI()
            app.include_router(router)
            checked = 0
            both_checked = asyncio.Event()

            class RacingSession(AsyncSession):
                async def execute(self, statement, *args, **kwargs):
                    nonlocal checked
                    result = await super().execute(statement, *args, **kwargs)
                    if getattr(statement, "is_select", False) and "users.email =" in str(statement):
                        checked += 1
                        if checked == 2:
                            both_checked.set()
                        await asyncio.wait_for(both_checked.wait(), timeout=3)
                    return result

            async def database():
                async with RacingSession(engine, expire_on_commit=False) as session:
                    yield session
            app.dependency_overrides[get_db] = database
            with patch("backend.api.auth.enforce_auth_limits", new=AsyncMock()):
                async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="https://test") as client:
                    async def register():
                        return await client.post("/auth/register", json={"email": "race@example.com", "password": "race-test-password"})
                    responses = await asyncio.gather(register(), register())
                    assert sorted(r.status_code for r in responses) == [201, 400]
                    assert "access_token=" in next(r for r in responses if r.status_code == 201).headers["set-cookie"]
            async with engine.begin() as conn:
                assert (await conn.execute(text("SELECT count(*) FROM users"))).scalar_one() == 1
                assert (await conn.execute(text("SELECT count(*) FROM auth_sessions"))).scalar_one() == 1
                await conn.run_sync(lambda sync: apply(sync, migration.downgrade))
                assert (await conn.execute(text("SELECT count(*) FROM users"))).scalar_one() == 1
    asyncio.run(run())


def test_concurrent_session_issuance_preserves_per_user_cap():
    async def run():
        async with isolated_database() as engine:
            async with engine.begin() as conn:
                await conn.run_sync(User.__table__.create)
                await conn.run_sync(AuthSession.__table__.create)
            async with AsyncSession(engine, expire_on_commit=False) as db:
                user = User(email="cap@example.com", hashed_password="unused")
                db.add(user)
                await db.commit()
                user_id = user.id

            async def issue():
                async with AsyncSession(engine, expire_on_commit=False) as db:
                    user = (await db.execute(select(User).where(User.id == user_id))).scalar_one()
                    token = await issue_session(db, user)
                    await db.commit()
                    return token
            tokens = await asyncio.gather(*(issue() for _ in range(25)))
            async with AsyncSession(engine) as db:
                digests = (await db.execute(select(AuthSession.token_digest))).scalars().all()
                assert len(digests) == 20
                assert all(digest in {token_digest(token) for token in tokens} for digest in digests)
    asyncio.run(run())
